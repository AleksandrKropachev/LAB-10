            {2, "Русские буквы запрещены вне строк"},

            {101, "Незакрытый комментарий"},
            {102, "Незакрытая строковая константа"},
            {103, "Пустая строковая константа"},

            {201, "Слишком длинный идентификатор"},
            {203, "Целое число вне диапазона"},

            {301, "Ожидался идентификатор"},
            {302, "Ожидалось :"},
            {303, "Ожидалось ;"},
            {304, "Ожидалось begin"},
            {305, "Ожидалось end"},
            {306, "Ожидалось :="},
            {307, "Ожидалась ."},
            {308, "Ошибка выражения"},
            {309, "Ожидалось do"},
            {310, "Ожидалось record"},
            {311, "Ожидалось var"},
