            {403, "Неизвестное поле записи"},
            {404, "Неизвестный тип"}
        };

        public static void Print(
            ushort code
        )
        {
            if (
                _messages.ContainsKey(code)
            )
            {
                Console.WriteLine(
                    $"{code} " +
                    $"{_messages[code]}"
                );
            }
            else
            {
                Console.WriteLine(
                    $"{code} Неизвестная ошибка"
                );
            }
        }
    }
}
